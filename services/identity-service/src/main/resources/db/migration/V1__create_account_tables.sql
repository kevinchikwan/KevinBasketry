-- identity-service schema (DESIGN.md Section 2).
-- Emails are stored lowercase (normalized by the application); the CHECK
-- constraints make a non-normalized email a hard error rather than a silent
-- case-sensitive duplicate.

CREATE TABLE account (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(255)             NOT NULL,
    password_hash   VARCHAR(255)             NOT NULL,
    buyer_active    BOOLEAN                  NOT NULL DEFAULT TRUE,
    merchant_id     BIGINT,                  -- reference to merchant-service; not a foreign key
    merchant_active BOOLEAN                  NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_account_email UNIQUE (email),
    CONSTRAINT ck_account_email_lowercase CHECK (email = LOWER(email))
);

-- Admin rows are created only by migrations, never by application code.
-- Email uniqueness across account and admin_account is checked at write time
-- (registration, merchant-link upsert, admin seed migrations), not by a
-- constraint, since it spans two tables.
CREATE TABLE admin_account (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255)             NOT NULL,
    password_hash VARCHAR(255)             NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_admin_account_email UNIQUE (email),
    CONSTRAINT ck_admin_account_email_lowercase CHECK (email = LOWER(email))
);
